// 获取某个部分的课程
export function getPartCourses(partId) {
  return courses.filter(c => c.part === partId)
}

// 获取课程所属部分
export function getCoursePart(courseId) {
  const course = courses.find(c => c.id === courseId)
  return course ? parts.find(p => p.id === course.part) : null
}
